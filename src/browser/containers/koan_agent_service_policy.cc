base::span<const ServiceRule> AgentServiceRules() {
  return kRules;
}

const ServiceRule* FindAgentServiceRule(std::string_view name) {
  auto it = std::lower_bound(kRules.begin(), kRules.end(), name,
                             [](const ServiceRule& rule, std::string_view n) {
                               return rule.name < n;
                             });
  return it != kRules.end() && it->name == name ? &*it : nullptr;
}

