constexpr bool IsSorted() {
  for (size_t i = 1; i < kRules.size(); ++i) {
    if (!(kRules[i - 1].name < kRules[i].name)) {
      return false;
    }
  }
  return true;
}
static_assert(IsSorted(), "kRules must be sorted by name and unique");

