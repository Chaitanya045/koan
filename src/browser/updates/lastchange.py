"""Stamps the Koan commit a build is made from (koan_lastchange.h).

The GN action //koan/browser/updates:lastchange runs this. It writes the
commit, its commit time and the GitHub repository of the clone's `origin`
remote into a header. It also writes a depfile naming the clone's
`logs/HEAD`, so ninja runs it again (and only then) when HEAD moves: a
commit, a pull or a checkout.

Without git, or outside a clone, the stamp is empty and Koan doesn't check
for updates.
"""

import argparse
import os
import re
import subprocess
import sys

# https://github.com/owner/name(.git), git@github.com:owner/name(.git),
# ssh://git@github.com/owner/name(.git).
_GITHUB_REMOTE = re.compile(
    r'^(?:https://(?:[^@/]+@)?github\.com/|git@github\.com:|'
    r'ssh://git@github\.com/)([A-Za-z0-9_.-]+)/([A-Za-z0-9_.-]+?)(?:\.git)?/?$')


def github_repo(remote_url):
  """'owner/name' for a github.com remote URL, else ''."""
  match = _GITHUB_REMOTE.match(remote_url.strip())
  return '%s/%s' % match.groups() if match else ''


def _git(repo_dir, *args):
  try:
    return subprocess.run(['git', '-C', repo_dir, *args],
                          check=True,
                          capture_output=True,
                          text=True).stdout.strip()
  except (OSError, subprocess.CalledProcessError):
    return ''


def read_stamp(repo_dir):
  """(commit, commit time in Unix seconds, GitHub repo, logs/HEAD path)."""
  line = _git(repo_dir, 'show', '-s', '--format=%H %ct', 'HEAD')
  parts = line.split()
  if len(parts) != 2 or not re.fullmatch(r'[0-9a-f]{40}', parts[0]):
    return '', 0, '', ''
  repo = github_repo(_git(repo_dir, 'remote', 'get-url', 'origin'))
  head_log = _git(repo_dir, 'rev-parse', '--path-format=absolute',
                  '--git-path', 'logs/HEAD')
  return parts[0], int(parts[1]), repo, head_log


def header(commit, commit_time, repo):
  return ('// Generated by //koan/browser/updates/lastchange.py. Do not edit.\n'
          '#ifndef KOAN_BROWSER_UPDATES_KOAN_LASTCHANGE_H_\n'
          '#define KOAN_BROWSER_UPDATES_KOAN_LASTCHANGE_H_\n\n'
          '#define KOAN_BUILD_COMMIT "%s"\n'
          '#define KOAN_BUILD_COMMIT_TIME %dLL\n'
          '#define KOAN_BUILD_GITHUB_REPO "%s"\n\n'
          '#endif  // KOAN_BROWSER_UPDATES_KOAN_LASTCHANGE_H_\n' %
          (commit, commit_time, repo))


def main(argv):
  parser = argparse.ArgumentParser(description=__doc__)
  parser.add_argument('--output', required=True)
  parser.add_argument('--depfile', required=True)
  args = parser.parse_args(argv)

  repo_dir = os.path.dirname(os.path.realpath(__file__))
  commit, commit_time, repo, head_log = read_stamp(repo_dir)
  with open(args.output, 'w') as f:
    f.write(header(commit, commit_time, repo))
  # Only files that exist: ninja treats a missing one as changed and would
  # rerun this, and relink, on every build. (Without a reflog the stamp only
  # follows checkouts of another branch.)
  if head_log and not os.path.exists(head_log):
    head_log = _git(repo_dir, 'rev-parse', '--path-format=absolute',
                    '--git-path', 'HEAD')
  deps = [head_log] if head_log and os.path.exists(head_log) else []
  with open(args.depfile, 'w') as f:
    f.write('%s: %s\n' % (args.output, ' '.join(d.replace(' ', '\\ ')
                                                 for d in deps)))
  return 0


if __name__ == '__main__':
  sys.exit(main(sys.argv[1:]))
