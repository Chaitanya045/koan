"""Builds the update key into the app (koan_update_public_key.h).

The GN action //koan/browser/updates:public_key_header runs this. It reads
koan_update_public_key.txt, the base64 of the raw 32-byte Ed25519 public key
that release.yml's signing key goes with (scripts/ci/update_manifest.py),
and writes it as a C++ array. A file that isn't exactly one such key fails
the build, so a bad edit can't ship an app that trusts nothing, or something
else.
"""

import argparse
import base64
import binascii
import sys

KEY_SIZE = 32


def read_key(text):
  """The raw key from the file's text; ValueError if it isn't one."""
  try:
    raw = base64.b64decode(text.strip(), validate=True)
  except (binascii.Error, ValueError) as e:
    raise ValueError('not base64: %s' % e)
  if len(raw) != KEY_SIZE:
    raise ValueError('%d bytes, not a %d-byte Ed25519 key' %
                     (len(raw), KEY_SIZE))
  return raw


def header(raw):
  rows = []
  for i in range(0, len(raw), 8):
    rows.append('    ' + ' '.join('0x%02x,' % b for b in raw[i:i + 8]))
  return ('// Generated by //koan/browser/updates/public_key_header.py from\n'
          '// koan_update_public_key.txt. Do not edit.\n'
          '#ifndef KOAN_BROWSER_UPDATES_KOAN_UPDATE_PUBLIC_KEY_H_\n'
          '#define KOAN_BROWSER_UPDATES_KOAN_UPDATE_PUBLIC_KEY_H_\n\n'
          '#include <stdint.h>\n\n'
          'namespace koan::updates {\n\n'
          'inline constexpr uint8_t kBuiltInPublicKey[%d] = {\n'
          '%s\n'
          '};\n\n'
          '}  // namespace koan::updates\n\n'
          '#endif  // KOAN_BROWSER_UPDATES_KOAN_UPDATE_PUBLIC_KEY_H_\n' %
          (KEY_SIZE, '\n'.join(rows)))


def main(argv):
  parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
  parser.add_argument('--input', required=True)
  parser.add_argument('--output', required=True)
  args = parser.parse_args(argv)
  with open(args.input) as f:
    text = f.read()
  try:
    raw = read_key(text)
  except ValueError as e:
    print('%s: %s' % (args.input, e), file=sys.stderr)
    return 1
  with open(args.output, 'w') as f:
    f.write(header(raw))
  return 0


if __name__ == '__main__':
  sys.exit(main(sys.argv[1:]))
