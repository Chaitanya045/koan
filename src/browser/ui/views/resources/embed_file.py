"""Writes a C++ header that holds a file's bytes as a constexpr array.

  embed_file.py <input> <output.h> <variable name> <header guard>
"""

import sys


def main():
    source, output, name, guard = sys.argv[1:5]
    with open(source, 'rb') as f:
        data = f.read()
    lines = []
    for i in range(0, len(data), 16):
        lines.append('    ' + ', '.join('0x%02x' % b for b in data[i:i + 16]) +
                     ',')
    with open(output, 'w') as f:
        f.write('// Generated by embed_file.py from %s. Do not edit.\n\n' %
                source.split('/')[-1])
        f.write('#ifndef %s\n#define %s\n\n' % (guard, guard))
        f.write('#include <cstdint>\n\n')
        f.write('namespace koan {\n\n')
        f.write('inline constexpr uint8_t %s[] = {\n' % name)
        f.write('\n'.join(lines))
        f.write('\n};\n\n}  // namespace koan\n\n#endif  // %s\n' % guard)


if __name__ == '__main__':
    main()
