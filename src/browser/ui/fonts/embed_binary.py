"""Writes a C++ header with binary files as byte arrays.

  embed_binary.py [--namespace=koan::fonts] <out.h> <kName>=<file> ...

Koan bundles Geist (OFL) this way, so the font needs no grit target or .pak
in upstream's resource lists and is the same bytes for the native UI and the
WebUI pages.
"""

import os
import sys


def main(argv):
  args = argv[1:]
  namespace = 'koan::fonts'
  if args and args[0].startswith('--namespace='):
    namespace = args.pop(0).split('=', 1)[1]
  out, entries = args[0], args[1:]
  guard = os.path.basename(out).upper().replace('.', '_') + '_'
  lines = [
      '// Generated by koan/browser/ui/fonts/embed_binary.py. Do not edit.',
      f'#ifndef KOAN_BROWSER_UI_FONTS_{guard}',
      f'#define KOAN_BROWSER_UI_FONTS_{guard}',
      '',
      '#include <cstddef>',
      '',
      f'namespace {namespace} {{',
      '',
  ]
  for entry in entries:
    name, path = entry.split('=', 1)
    with open(path, 'rb') as f:
      data = f.read()
    lines.append(f'inline constexpr unsigned char {name}[] = {{')
    for i in range(0, len(data), 24):
      lines.append('    ' + ','.join(str(b) for b in data[i:i + 24]) + ',')
    lines.append('};')
    lines.append(f'inline constexpr size_t {name}Size = sizeof({name});')
    lines.append('')
  lines += [
      f'}}  // namespace {namespace}',
      '',
      f'#endif  // KOAN_BROWSER_UI_FONTS_{guard}',
      '',
  ]
  with open(out, 'w', encoding='utf-8') as f:
    f.write('\n'.join(lines))


if __name__ == '__main__':
  main(sys.argv)
