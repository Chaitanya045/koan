"""Generates src/browser/ui/color/koan_shadcn_palettes.inc from shadcn/ui.

The base colours (Neutral, Zinc, Slate, Stone, Gray) come from
`baseColorsV4` in apps/v4/registry/_legacy-base-colors.ts, the accent themes
from apps/v4/registry/themes.ts of https://github.com/shadcn-ui/ui (MIT).
The OKLCH values are copied as they are; koan_oklch.cc converts them to sRGB
when the palettes are resolved, so nothing is rounded by hand.

  curl -sLO https://raw.githubusercontent.com/shadcn-ui/ui/main/apps/v4/registry/_legacy-base-colors.ts
  curl -sLO https://raw.githubusercontent.com/shadcn-ui/ui/main/apps/v4/registry/themes.ts
  scripts/gen_shadcn_palettes.py _legacy-base-colors.ts themes.ts \\
      > src/browser/ui/color/koan_shadcn_palettes.inc
"""

import re
import sys

# The tokens Koan uses, in koan_tokens.h's order (Token enum).
TOKENS = [
    'background', 'foreground', 'card', 'card-foreground', 'popover',
    'popover-foreground', 'primary', 'primary-foreground', 'secondary',
    'secondary-foreground', 'muted', 'muted-foreground', 'accent',
    'accent-foreground', 'destructive', 'border', 'input', 'ring', 'sidebar',
    'sidebar-foreground', 'sidebar-primary', 'sidebar-primary-foreground',
    'sidebar-accent', 'sidebar-accent-foreground', 'sidebar-border',
    'sidebar-ring',
]
BASES = ['neutral', 'zinc', 'slate', 'stone', 'gray']
ACCENTS = ['blue', 'green', 'orange', 'red', 'rose', 'violet', 'yellow']

ENTRY = re.compile(
    r'^\s*"?([a-z0-9-]+)"?:\s*"oklch\(\s*([0-9.]+)\s+([0-9.]+)\s+([0-9.]+)'
    r'(?:\s*/\s*([0-9.]+)(%?))?\s*\)"')


def parse_entry(line):
  m = ENTRY.match(line)
  if not m:
    return None
  name, l, c, h, a, pct = m.groups()
  alpha = 1.0
  if a is not None:
    alpha = float(a) / 100.0 if pct else float(a)
  return name, (float(l), float(c), float(h), alpha)


def parse_bases(text):
  start = text.index('export const baseColorsV4')
  end = text.index('export const baseColorsOKLCH')
  result = {}
  base = mode = None
  for line in text[start:end].splitlines():
    m = re.match(r'^  ([a-z]+): \{', line)
    if m:
      base = m.group(1)
      result[base] = {}
      continue
    m = re.match(r'^    (light|dark): \{', line)
    if m:
      mode = m.group(1)
      result[base][mode] = {}
      continue
    e = parse_entry(line)
    if e and base and mode:
      result[base][mode][e[0]] = e[1]
  return result


def parse_accents(text):
  result = {}
  name = mode = None
  for line in text.splitlines():
    m = re.match(r'^    name: "([a-z]+)"', line)
    if m:
      name = m.group(1)
      result[name] = {}
      continue
    m = re.match(r'^      (light|dark): \{', line)
    if m:
      mode = m.group(1)
      result[name][mode] = {}
      continue
    e = parse_entry(line)
    if e and name and mode:
      result[name][mode][e[0]] = e[1]
  return result


def num(v):
  s = ('%.4f' % v).rstrip('0')
  return s + '0' if s.endswith('.') else s


def fmt(color):
  return '{%s}' % ', '.join(num(v) + 'f' for v in color)


def main():
  bases = parse_bases(open(sys.argv[1]).read())
  accents = parse_accents(open(sys.argv[2]).read())

  out = []
  out.append('// Generated by scripts/gen_shadcn_palettes.py from shadcn/ui '
             '(MIT, Copyright (c) 2023 shadcn).')
  out.append('// Do not edit.')
  out.append('')
  out.append('// Each palette lists the tokens in Token order (koan_tokens.h).')
  for base in BASES:
    for mode in ('light', 'dark'):
      values = bases[base][mode]
      out.append('constexpr OklchColor k%s%s[kTokenCount] = {' %
                 (base.capitalize(), mode.capitalize()))
      for token in TOKENS:
        out.append('    %s,  // %s' % (fmt(values[token]), token))
      out.append('};')
  out.append('')
  out.append('// Accent themes override only the tokens they list.')
  out.append('struct AccentOverride {')
  out.append('  Token token;')
  out.append('  OklchColor color;')
  out.append('};')
  for accent in ACCENTS:
    for mode in ('light', 'dark'):
      values = accents[accent][mode]
      rows = [(t, values[t]) for t in TOKENS if t in values]
      out.append('constexpr AccentOverride k%s%s[] = {' %
                 (accent.capitalize(), mode.capitalize()))
      for token, color in rows:
        enum = 'Token::k' + ''.join(p.capitalize() for p in token.split('-'))
        out.append('    {%s, %s},' % (enum, fmt(color)))
      out.append('};')
  print('\n'.join(out))


if __name__ == '__main__':
  main()
